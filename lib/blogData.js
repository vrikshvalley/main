// Helper function to get blog by slug
export function getBlogBySlug(slug) {
  return blogPosts.find((post) => post.slug === slug);
}

// Helper function to get related blogs (same category, excluding current)
export function getRelatedBlogs(currentSlug, limit = 3) {
  const currentBlog = getBlogBySlug(currentSlug);
  if (!currentBlog) return [];

  return blogPosts
    .filter(
      (post) =>
        post.slug !== currentSlug && post.category === currentBlog.category
    )
    .slice(0, limit);
}

// Helper function to get recent blogs
export function getRecentBlogs(limit = 3) {
  return blogPosts
    .sort((a, b) => new Date(b.date) - new Date(a.date))
    .slice(0, limit);
}

// Helper function to get all categories
export function getAllCategories() {
  return [...new Set(blogPosts.map((post) => post.category))];
}
